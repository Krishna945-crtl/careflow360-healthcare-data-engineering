-- Run with a Snowflake role authorized to create database/schema and tables.
-- No synthetic dataset is loaded automatically. See scripts/load_snowflake.py.
-- CAREFLOW_DB is already created in Snowflake.
-- No database will be created by this file.
CREATE SCHEMA IF NOT EXISTS CAREFLOW_DB.RAW;
CREATE SCHEMA IF NOT EXISTS CAREFLOW_DB.STAGING;
CREATE SCHEMA IF NOT EXISTS CAREFLOW_DB.MARTS;
CREATE TABLE IF NOT EXISTS CAREFLOW_DB.RAW.CLINICS (
  CLINIC_ID VARCHAR, NAME VARCHAR, REGION VARCHAR, INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP());
CREATE TABLE IF NOT EXISTS CAREFLOW_DB.RAW.PATIENTS (
  PATIENT_ID VARCHAR, NAME VARCHAR, BIRTH_YEAR INTEGER, CLINIC_ID VARCHAR, INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP());
CREATE TABLE IF NOT EXISTS CAREFLOW_DB.RAW.APPOINTMENTS (
  APPOINTMENT_ID VARCHAR, PATIENT_ID VARCHAR, CLINIC_ID VARCHAR, SCHEDULED_DATE DATE,
  STATUS VARCHAR, TYPE VARCHAR, UPDATED_AT TIMESTAMP_TZ, INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP());
CREATE TABLE IF NOT EXISTS CAREFLOW_DB.RAW.ENCOUNTERS (
  ENCOUNTER_ID VARCHAR, APPOINTMENT_ID VARCHAR, ENCOUNTERED_ON DATE,
  UPDATED_AT TIMESTAMP_TZ, INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP());
